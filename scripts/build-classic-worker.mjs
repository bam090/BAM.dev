import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { Script } from "node:vm";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const outputPath = path.join(root, "src/workers/javascript-code-runner.classic.js");

async function source(relativePath, imports, exports) {
  const text = await readFile(path.join(root, relativePath), "utf8");
  const actualImports = text.match(/^import\b.*$/gmu) ?? [];
  const actualExports = text.match(/^export .*$/gmu) ?? [];
  if (JSON.stringify(actualImports) !== JSON.stringify(imports) ||
      JSON.stringify(actualExports) !== JSON.stringify(exports) ||
      /\b(?:importScripts|import)\s*\(/u.test(text)) {
    throw new Error(`${relativePath}: import/export 형태가 변경되었습니다. classic Worker 생성을 검토하세요.`);
  }
  let result = text;
  for (const statement of imports) result = result.replace(`${statement}\n`, "");
  result = result.replace(/^export (?=(?:const|async function|function)\b)/gmu, "");
  result = result.replace(/^export \{[^\n]+\};\n?/gmu, "");
  return result.trimEnd();
}

