new Script(output, { filename: outputPath });

export async function checkClassicWorker() {
  if (await readFile(outputPath, "utf8") !== output) {
    throw new Error("classic Worker 자산이 원본과 다릅니다. node scripts/build-classic-worker.mjs를 실행하세요.");
  }
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  if (process.argv[2] === "--check" && process.argv.length === 3) {
    await checkClassicWorker();
  } else if (process.argv.length === 2) {
    await writeFile(outputPath, output);
  } else {
    throw new Error("사용법: node scripts/build-classic-worker.mjs [--check]");
  }
}
